#!/bin/bash
# Packs the real Unity PNGs, the phase5-ui pixel fonts and the bench layout into assets.js (base64), so index.html works
# from file:// (a file:// page cannot read pixels of its own image files or load font files: they count as cross-origin).
# Run from anywhere: bash docs/mockup/hd2d/build.sh     (writes only docs/mockup/hd2d/assets.js)
cd "$(dirname "$0")"
python3 - <<'PY'
import base64, json, os, sys
art = '../../../Athanor/Assets/Art/'
names = {
  'Background': ['workshop_wall', 'window_d1', 'window_d2', 'window_d3', 'window_d4', 'window_d5', 'moon_shaft', 'workshop_table', 'candle', 'flame_small', 'logs'],
  'Fx': ['glow', 'tile_ring_0', 'tile_ring_1', 'tile_ring_2'],
  'Icons': ['salt_crystal', 'ember_coal', 'brine', 'quicksilver', 'mandrake', 'glowmoss', 'lightning_sand', 'deep_tear', 'bone_ash', 'iron_ore'],
  'UI': ['hud_left', 'hud_right', 'rack', 'note', 'corner', 'book', 'ignite_up', 'card', 'card_sel', 'bar_fill'],
}
img, missing = {}, []
for folder, ns in names.items():
    for n in ns:
        p = art + folder + '/' + n + '.png'
        if not os.path.exists(p): missing.append(p); continue
        img[n] = 'data:image/png;base64,' + base64.b64encode(open(p, 'rb').read()).decode()
if missing: print('missing:', missing); sys.exit(1)
fonts = {k: base64.b64encode(open('../phase5-ui/f/' + v, 'rb').read()).decode() for k, v in
         {'Alagard': 'Alagard.ttf', 'BitPotion': 'BitPotion.ttf', 'PixOp8': 'PixelOperator8.ttf', 'PixOpB': 'PixelOperator-Bold.ttf'}.items()}
layout = json.load(open('../../../Athanor/Assets/Resources/layout.json'))
with open('assets.js', 'w') as f:
    f.write('// generated by build.sh from Athanor/Assets/Art, docs/mockup/phase5-ui/f and Resources/layout.json; do not edit\n')
    f.write('window.ART = ' + json.dumps({'img': img, 'font': fonts, 'layout': {k: layout[k] for k in ('tiles', 'placed', 'candles')}}) + ';\n')
print('assets.js', os.path.getsize('assets.js'), 'bytes,', len(img), 'images,', len(fonts), 'fonts')
PY
