#!/bin/bash
# Packs the real Unity PNGs and the pixel fonts into assets.js (base64), so index.html works from file:// too
# (a file:// page cannot upload its own image files to WebGL or load font files: the browser treats them as cross-origin).
# Run from anywhere: bash docs/mockup/depth/build.sh
cd "$(dirname "$0")"
python3 - <<'PY'
import base64, json, os
art = '../../../Athanor/Assets/Art/'
names = {
  'Background': ['workshop_wall', 'window', 'moon_shaft', 'workshop_table', 'candle'] + ['flame_small_%d' % i for i in range(8)],
  'Fx': ['glow', 'tile_ring_0', 'tile_ring_1', 'tile_ring_2'],
  'Icons': ['brine', 'sulfur', 'salt_crystal', 'ember_coal', 'quicksilver', 'mandrake', 'glowmoss', 'moonpetal', 'spark_quartz', 'iron_ore'],
  'UI': ['hud_left', 'hud_right', 'rack', 'note', 'corner', 'book', 'ignite_up', 'card', 'card_sel', 'bar_fill'],
}
img = {}
for folder, ns in names.items():
    for n in ns:
        img[n] = 'data:image/png;base64,' + base64.b64encode(open(art + folder + '/' + n + '.png', 'rb').read()).decode()
fonts = {k: base64.b64encode(open('../f/' + v, 'rb').read()).decode() for k, v in
         {'Alagard': 'Alagard.ttf', 'BitPotion': 'BitPotion.ttf', 'PixOp8': 'PixelOperator8.ttf'}.items()}
layout = json.load(open('../../../Athanor/Assets/Resources/layout.json'))
with open('assets.js', 'w') as f:
    f.write('// generated by build.sh from Athanor/Assets/Art, docs/mockup/f and Resources/layout.json; do not edit\n')
    f.write('window.ART = ' + json.dumps({'img': img, 'font': fonts, 'layout': {k: layout[k] for k in ('tiles', 'placed', 'candles')}}) + ';\n')
print('assets.js', os.path.getsize('assets.js'), 'bytes,', len(img), 'images')
PY
